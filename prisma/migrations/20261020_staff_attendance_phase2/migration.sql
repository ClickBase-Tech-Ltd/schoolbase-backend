CREATE TABLE `StaffAttendancePolicy` (
  `id` VARCHAR(191) NOT NULL,
  `schoolId` VARCHAR(191) NOT NULL,
  `name` VARCHAR(191) NOT NULL DEFAULT 'Standard attendance',
  `shiftStartTime` VARCHAR(191) NOT NULL DEFAULT '08:30',
  `checkInGraceMinutes` INTEGER NOT NULL DEFAULT 15,
  `checkOutCutoffMinutes` INTEGER NOT NULL DEFAULT 540,
  `requireCheckout` BOOLEAN NOT NULL DEFAULT true,
  `workDays` VARCHAR(191) NOT NULL DEFAULT '1,2,3,4,5',
  `effectiveFrom` DATE NOT NULL,
  `effectiveTo` DATE NULL,
  `isActive` BOOLEAN NOT NULL DEFAULT true,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `staff_att_policy_effective_key` (`schoolId`, `name`, `effectiveFrom`),
  INDEX `staff_att_policy_active_dates_idx` (`schoolId`, `isActive`, `effectiveFrom`, `effectiveTo`),
  CONSTRAINT `StaffAttendancePolicy_schoolId_fkey` FOREIGN KEY (`schoolId`) REFERENCES `School` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `StaffAttendanceRecord` (
  `id` VARCHAR(191) NOT NULL,
  `schoolId` VARCHAR(191) NOT NULL,
  `employeeId` VARCHAR(191) NOT NULL,
  `policyId` VARCHAR(191) NULL,
  `date` DATE NOT NULL,
  `shiftKey` VARCHAR(191) NOT NULL DEFAULT 'DEFAULT',
  `checkInAt` DATETIME(3) NULL,
  `checkOutAt` DATETIME(3) NULL,
  `status` ENUM('PRESENT', 'LATE', 'MISSING_CHECKOUT', 'ABSENT') NOT NULL DEFAULT 'PRESENT',
  `reason` TEXT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `staff_att_record_employee_date_shift_key` (`schoolId`, `employeeId`, `date`, `shiftKey`),
  INDEX `staff_att_record_school_date_status_idx` (`schoolId`, `date`, `status`),
  INDEX `staff_att_record_employee_date_idx` (`employeeId`, `date`),
  INDEX `staff_att_record_policy_date_idx` (`schoolId`, `policyId`, `date`),
  CONSTRAINT `StaffAttendanceRecord_schoolId_fkey` FOREIGN KEY (`schoolId`) REFERENCES `School` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `StaffAttendanceRecord_employeeId_fkey` FOREIGN KEY (`employeeId`) REFERENCES `EmployeeProfile` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `StaffAttendanceRecord_policyId_fkey` FOREIGN KEY (`policyId`) REFERENCES `StaffAttendancePolicy` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `StaffAttendanceEvent` (
  `id` VARCHAR(191) NOT NULL,
  `schoolId` VARCHAR(191) NOT NULL,
  `attendanceId` VARCHAR(191) NOT NULL,
  `employeeId` VARCHAR(191) NOT NULL,
  `actorUserId` VARCHAR(191) NULL,
  `eventType` VARCHAR(191) NOT NULL,
  `status` ENUM('PRESENT', 'LATE', 'MISSING_CHECKOUT', 'ABSENT') NULL,
  `reason` TEXT NOT NULL,
  `idempotencyKey` VARCHAR(191) NULL,
  `beforeSnapshot` JSON NULL,
  `afterSnapshot` JSON NULL,
  `details` JSON NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `staff_att_event_idempotency_key` (`schoolId`, `idempotencyKey`),
  INDEX `staff_att_event_record_date_idx` (`schoolId`, `attendanceId`, `createdAt`),
  INDEX `staff_att_event_employee_date_idx` (`employeeId`, `createdAt`),
  CONSTRAINT `StaffAttendanceEvent_schoolId_fkey` FOREIGN KEY (`schoolId`) REFERENCES `School` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `StaffAttendanceEvent_attendanceId_fkey` FOREIGN KEY (`attendanceId`) REFERENCES `StaffAttendanceRecord` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `StaffAttendanceEvent_employeeId_fkey` FOREIGN KEY (`employeeId`) REFERENCES `EmployeeProfile` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `StaffAttendanceEvent_actorUserId_fkey` FOREIGN KEY (`actorUserId`) REFERENCES `User` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
