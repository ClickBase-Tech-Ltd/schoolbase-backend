CREATE TABLE `SchoolReview` (
  `id` VARCHAR(191) NOT NULL,
  `schoolId` VARCHAR(191) NOT NULL,
  `submittedByUserId` VARCHAR(191) NULL,
  `rating` INTEGER NOT NULL,
  `reviewText` VARCHAR(2000) NULL,
  `status` ENUM('PENDING', 'APPROVED', 'REJECTED') NOT NULL DEFAULT 'PENDING',
  `publishConsent` BOOLEAN NOT NULL DEFAULT false,
  `schoolNameConsent` BOOLEAN NOT NULL DEFAULT false,
  `schoolLogoConsent` BOOLEAN NOT NULL DEFAULT false,
  `consentGrantedAt` DATETIME(3) NULL,
  `consentRevokedAt` DATETIME(3) NULL,
  `moderatedByUserId` VARCHAR(191) NULL,
  `moderatedAt` DATETIME(3) NULL,
  `moderationNote` VARCHAR(2000) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  INDEX `SchoolReview_status_createdAt_idx` (`status`, `createdAt`),
  INDEX `SchoolReview_status_rating_createdAt_idx` (`status`, `rating`, `createdAt`),
  INDEX `SchoolReview_submittedByUserId_idx` (`submittedByUserId`),
  UNIQUE INDEX `SchoolReview_schoolId_key` (`schoolId`),
  PRIMARY KEY (`id`),
  CONSTRAINT `SchoolReview_schoolId_fkey` FOREIGN KEY (`schoolId`) REFERENCES `School` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `SchoolReview_submittedByUserId_fkey` FOREIGN KEY (`submittedByUserId`) REFERENCES `User` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `SchoolReview_moderatedByUserId_fkey` FOREIGN KEY (`moderatedByUserId`) REFERENCES `User` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;